var ErrUnsupportedTimeZone = errors.New("provided time zone is not supported")

func mustLoadTimeZone(timeZoneIANAName string) string {
	loc, err := time.LoadLocation(timeZoneIANAName)
	if err != nil {
		panic(err)
	}
	return loc.String()
}

// Validate confirms that a time zone is a supported IANA format (case sensitive) time zone
func Validate(zone string) bool {
	return sequence.Contains(supportedTimeZones, zone)
}

// GetSupportedZones returns a list of supported IANA Time Zones
func GetSupportedZones() []string {
	return supportedTimeZones
}

// LoadSupportedZone returns the loaded location for a case insensitive IANA time zone string or an error if it is not found in the supported list
func LoadSupportedZone(zone string) (time.Location, error) {
	loc, ok := supportedLowerCaseZoneMap[strings.ToLower(zone)]
	if !ok {
		return loc, fmt.Errorf("failed to load location for %s: %w", zone, ErrUnsupportedTimeZone)
	}

	return loc, nil
}

