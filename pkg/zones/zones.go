// supportedLowerCaseZoneMap contains a mapping of lower-cased time zones to their time.Location struct counterparts
var supportedLowerCaseZoneMap = sequence.Reduce(supportedTimeZones, map[string]time.Location{}, func(acc map[string]time.Location, el string) map[string]time.Location {
	loc, _ := time.LoadLocation(el)
	acc[strings.ToLower(el)] = ptr.Deref(loc)
	return acc
})
